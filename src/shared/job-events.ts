import { logger } from "./app-logger.js";

/**
 * @description Redacts only the credential-bearing query params of a presigned URL, leaving structural params (expiry, algorithm, date, etc.) visible for debugging.
 *
 * Provider-agnostic: works for AWS S3, MinIO, GCS, Azure SAS, or any other presigned-URL scheme by allow-listing known sensitive param names rather than assuming one provider's format.
 */
export function redactPresignedUrl(value: string): string {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    logger.warn("Unable to redact presigned upload URL; logging full URL!", {
      context: "SharedUtils",
    });
    return value;
  }

  /**
   * @description Sensitive query param names (case-insensitive).
   */
  const SENSITIVE_PRESIGNED_URL_PARAMS = new Set([
    // AWS SigV4 (S3, MinIO, R2, and other S3-compatible providers): https://docs.aws.amazon.com/IAM/latest/UserGuide/reference_sigv.html
    "x-amz-signature",
    "x-amz-credential",
    "x-amz-security-token",
    // GCS V4 signing: https://docs.cloud.google.com/storage/docs/access-control/signing-urls-with-helpers
    "x-goog-signature",
    "x-goog-credential",
    // Azure SAS: https://learn.microsoft.com/en-us/rest/api/storageservices/delegate-access-with-shared-access-signature
    "sig", // signature
    "se", // signed expiry can arguably stay, but treat conservatively
    "sr", // signed resource
    "token",
  ]);
  const params = new URLSearchParams(url.search);

  for (const key of params.keys()) {
    if (SENSITIVE_PRESIGNED_URL_PARAMS.has(key.toLowerCase())) {
      params.set(key, "***");
    }
  }

  const query = params.toString();
  const result = `${url.origin}${url.pathname}${query ? `?${query}` : ""}`;

  return result;
}

export type SynthesizeJobState =
  | "queued"
  | "generating"
  | "uploading"
  | "completed"
  | "failed"
  | "retrying";

export interface SynthesizeJobEvent {
  attempt: number;
  instanceId: string;
  jobId: string;
  /** @description Piper model name */
  modelName: string;
  state: SynthesizeJobState;
  textCharacterCount: number;
  traceId?: string;
  /** @description How long it waited in the queue? */
  queueWaitMs?: number;
  /** @description How long it took to generate TTS audio file */
  generationDurationMs?: number;
  /** @description How long it took to upload the audio file */
  uploadDurationMs?: number;
  /** @description How long it took in total to synthesize */
  totalDurationMs?: number;
  fileSizeBytes?: number;
  fileSizeMb?: number;
  errorCode?: string;
  errorMessage?: string;
  failedAt?: string;
  retryCount?: number;
  /** @description How many times at max we should try */
  maxAttempts?: number;
  /** It is the stage in which the synthesize job is in, it can be `SynthesizeErrorCode` or any other string */
  stage?: string;
  /** @description The presigned URL generated by the client */
  uploadUrl?: string;
}
